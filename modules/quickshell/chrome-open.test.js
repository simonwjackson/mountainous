const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const path = require("node:path");
const source = process.argv[2] || __dirname;
const qml = fs.readFileSync(path.join(source, "shell.qml"), "utf8");
const policy = {};
if (fs.existsSync(path.join(source, "chrome-open.js"))) vm.runInNewContext(fs.readFileSync(path.join(source, "chrome-open.js"), "utf8").replace(/^\.pragma library\s*$/m, ""), policy);
const screen = {name: "first"}, second = {name: "second"};
const deferred = [];
const root = {desktops: {}, pendingChrome: {}, primaryScreen: () => screen, focusedScreen: () => screen};
const scope = {root, Theme: {name: "platinum"}, ChromeOpen: policy, Qt: {callLater: fn => deferred.push(fn)}};
const start = qml.indexOf("    function openChrome(");
vm.runInNewContext(qml.slice(start, qml.indexOf("    // Super+Tab", start)), scope);
root.flushChrome = scope.flushChrome;
root.openChrome = scope.openChrome;
const calls = [];
const desktop = (theme, name) => ({active: true, theme: {id: theme}, open: control => calls.push([name, control])});
root.openChrome("apple"); // IPC registered, asynchronous Desktop not loaded.
root.desktops.first = desktop("platinum", "first");
if (root.flushChrome) root.flushChrome();
assert.deepEqual(calls, [["first", "apple"]], "first open survives a Desktop that is not ready yet");
root.openChrome("apple"); root.openChrome("app");
while (deferred.length) deferred.shift()();
assert.deepEqual(calls.at(-1), ["first", "app"], "latest pending call per screen wins");
const count = calls.length;
root.desktops.first.active = false; root.openChrome("apple");
root.flushChrome(); assert.equal(calls.length, count, "inactive Desktop cannot consume a request");
root.desktops.first.active = true; root.flushChrome(); assert.equal(calls.length, count + 1);
root.desktops.first = desktop("platinum", "first");
root.openChrome("apple");
// The real shell clears this queue on Theme.nameChanged.
root.pendingChrome = {};
scope.Theme.name = "win98";
root.openChrome("start"); root.flushChrome();
assert.equal(calls.length, count + 1, "old theme cannot consume a new theme's pending open");
root.desktops.first = desktop("win98", "first"); root.flushChrome();
assert.deepEqual(calls.at(-1), ["first", "start"], "Win98 uses the same queue");
root.focusedScreen = () => second; root.openChrome("start");
root.desktops.second = desktop("win98", "second"); root.flushChrome();
assert.deepEqual(calls.at(-1), ["second", "start"], "the captured screen is retained");
root.flushChrome(); assert.equal(Object.keys(root.pendingChrome).length, 0, "requests are consumed only once");
assert.match(qml, /function onNameChanged\(\)\s*\{\s*root\.pendingChrome = \{\};/, "a theme change drops pending opens");
console.log("chrome-open: cold start, latest per screen, inactive/replaced Desktop and Win98 pass");
