const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const path = require("node:path");
const dir = process.argv[2] || __dirname;
const policy = {};
vm.runInNewContext(fs.readFileSync(path.join(dir, "favicon.js"), "utf8").replace(/^\.pragma library\s*$/m, ""), policy);
const icon = (size, url = `https://site.test/${size}.png`) => ({url, sizes: `${size}x${size}`});
assert.equal(policy.choose([icon(16), icon(32), icon(180)], 24), icon(32).url);
assert.equal(policy.choose([icon(16), icon(32), icon(180)], 32), icon(32).url);
assert.equal(policy.choose([icon(16), icon(32), icon(180)], 48), icon(180).url);
assert.equal(policy.choose([icon(16), icon(32)], 64), icon(32).url, "largest undersized source wins");
assert.equal(policy.choose([{url: "https://site.test/multi.ico", sizes: ""}, icon(16)], 24), "https://site.test/multi.ico", "unknown ICO can contain a suitable frame");
assert.equal(policy.choose([icon(16), {url: "https://site.test/vector.svg", sizes: "any"}], 24), "https://site.test/vector.svg");
assert.equal(policy.choose([icon(16, "file:///secret"), icon(32, "javascript:alert(1)"), {url: 42}], 24), "");
assert.equal(policy.choose([{url: "https://site.test/multi.png", sizes: "16x16 48x48"}, icon(64)], 24), "https://site.test/multi.png");
assert.equal(policy.choose([{url: "https://site.test/bad.png", sizes: "NaNxNaN"}, icon(32)], 24), icon(32).url);
assert.equal(policy.choose([{url: "https://site.test/bad.png", sizes: {toString: "invalid"}}, icon(32)], 24), icon(32).url, "malformed manifest sizes cannot throw");
const frames = [256, 64, 48, 40, 32, 24, 20, 16].map((size, frame) => ({size, frame}));
assert.equal(policy.frameFor(frames, 24), 5, "Teams descending ICO order selects the exact 24px frame");
assert.equal(policy.frameFor(frames, 30), 4);
assert.equal(policy.frameFor([16, 32, 48].map((size, frame) => ({size, frame})), 24), 1, "ascending ICO order also works");
assert.equal(policy.frameFor(frames, 300), 0);
assert.equal(policy.frameFor([], 24), 0);
assert.equal(policy.smoothFor(48, 24), true, "downscale smoothly from native pixels");
assert.equal(policy.smoothFor(24, 24), false, "exact pixels need no filter");
assert.equal(policy.smoothFor(16, 24), false, "undersized images use nearest neighbour, including fractional scales");
assert.equal(policy.installed("chrome-ompifgpmddkgmclendfeacglnodjjndh-Default", "/home/simon/icon.png"), "file:///home/simon/icon.png");
assert.equal(policy.installed("chrome-ompifgpmddkgmclendfeacglnodjjndh-Default", "chrome-icon"), "");
assert.equal(policy.installed("chrome-example.test__-Default", "/home/simon/icon.png"), "");
console.log("favicon: device-pixel source choice, scheme validation, unordered ICO frames, sampling and installed PWA icons pass");

// Run the production metadata controller, including navigation races and
// evaluation failures. Discovery itself runs in real Chromium in favicon-runtime.py.
const CdpTarget = {};
vm.runInNewContext(fs.readFileSync(path.join(dir, "cdp-target.js"), "utf8").replace(/^\.pragma library\s*$/m, ""), CdpTarget);
const page = {id: "a", title: "Site", url: "https://site.test/", favicon: "https://site.test/favicon.ico", ws: "ws://localhost/page/a", endpoint: "normal"};
const root = {pages: [page], pageIcons: {}, focusMap: {}};
const qml = fs.readFileSync(path.join(dir, "CdpBrowser.qml"), "utf8");
const scope = {root, CdpTarget, Favicon: policy};
vm.runInNewContext(qml.slice(qml.indexOf("function faviconFor("), qml.indexOf("    Instantiator {")), scope);
const window = {appId: "chromium-browser", title: "Site - Chromium"};
assert.equal(scope.faviconFor(window, 24), page.favicon, "CDP URL is available before discovery");
scope.recordPageIcons(page, [icon(16), icon(32), icon(180)]);
assert.equal(scope.faviconFor(window, 24), icon(32).url);
assert.equal(scope.faviconFor(window, 48), icon(180).url, "surfaces choose independently from shared metadata");
const navigated = {...page, url: "https://site.test/new", favicon: "https://site.test/new.ico"};
root.pages = [navigated];
assert.equal(scope.faviconFor(window, 24), navigated.favicon, "old declared icons cannot leak into a new navigation");
const beforeLateReply = root.pageIcons.a;
scope.recordPageIcons(page, [icon(180)]);
assert.equal(root.pageIcons.a, beforeLateReply, "late metadata cannot overwrite the current entry");
scope.recordPageIcons(navigated, null);
assert.equal(root.pageIcons.a.key, policy.pageKey(navigated), "errors are cached for this navigation too");
assert.equal(scope.faviconFor(window, 24), navigated.favicon, "evaluation errors retain the existing CDP fallback");
root.pages = [];
scope.recordPageIcons(navigated, [icon(32)]);
assert.equal(root.pageIcons.a.icons.length, 0, "a closed target cannot publish a late response");
assert.equal(scope.faviconFor(window, 24), "");
console.log("favicon: production metadata cache, per-surface choice, stale navigation/closed target rejection and error fallback pass");
