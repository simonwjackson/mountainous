#!/usr/bin/env bash
# Write notification-schema.js, the QML-importable copy of the socket schema.
#
#   notification-schema-js.sh packages/notify-sync/schema/ui-socket.v1.json > notification-schema.js
#
# The one generator for it: modules/notification-view.nix runs it for the
# installed file and the check, and notification-dev/capture.sh for the
# headless session. The output is generated; never edit it by hand.
set -euo pipefail
schema=${1:?usage: notification-schema-js.sh SCHEMA}
printf '.pragma library\n'
printf '// Generated by notification-schema-js.sh from ui-socket.v1.json. Do not edit.\n'
printf 'var schema = '
cat "$schema"
printf ';\n'
